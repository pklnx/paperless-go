-- +goose Up
-- Users and login (#3, part 1): the login columns on the minimal users
-- table from 00002, and login sessions. No path created users before this
-- migration, so it refuses a table that has rows: those users would have no
-- password.
-- +goose StatementBegin
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM users) THEN
        RAISE EXCEPTION 'the users table is not empty: users created before login existed have no password'
            USING HINT = 'Remove those users, then run the migration again.';
    END IF;
END;
$$;
-- +goose StatementEnd

-- Names are lowercase login names; passwords are only stored as Argon2id
-- hashes (PHC string format).
ALTER TABLE users
    ADD COLUMN password_hash        TEXT        NOT NULL,
    -- Set for passwords generated by an admin: the user must choose their
    -- own password before they can do anything else.
    ADD COLUMN must_change_password BOOLEAN     NOT NULL DEFAULT FALSE,
    ADD COLUMN locked_at            TIMESTAMPTZ,
    ADD COLUMN password_changed_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    ADD COLUMN last_login_at        TIMESTAMPTZ,
    ADD CONSTRAINT users_name_format CHECK (name ~ '^[a-z0-9._-]{1,64}$');

-- Login sessions. The id is the SHA-256 of the cookie token, so a leaked
-- database does not reveal usable tokens. Sessions go with their user
-- (ON DELETE CASCADE), as every later auth table does: only owned data
-- (documents and metadata, ON DELETE RESTRICT) keeps a user from being
-- removed.
CREATE TABLE sessions (
    id           BYTEA       PRIMARY KEY CHECK (length(id) = 32),
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    expires_at   TIMESTAMPTZ NOT NULL,
    user_agent   TEXT        NOT NULL DEFAULT ''
);
CREATE INDEX sessions_user_id_idx ON sessions (user_id);

-- +goose Down
-- Rolling back drops every password, and the Up refuses a users table with
-- rows, so a rollback with users could not be undone: refuse it as well.
-- +goose StatementBegin
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM users) THEN
        RAISE EXCEPTION 'users exist: rolling back would drop their passwords and logins'
            USING HINT = 'Restore a backup made before the upgrade instead.';
    END IF;
END;
$$;
-- +goose StatementEnd
DROP TABLE sessions;
ALTER TABLE users
    DROP CONSTRAINT users_name_format,
    DROP COLUMN last_login_at,
    DROP COLUMN password_changed_at,
    DROP COLUMN locked_at,
    DROP COLUMN must_change_password,
    DROP COLUMN password_hash;
