// ErrLastAdmin is returned when a change would leave no unlocked admin.
var ErrLastAdmin = errors.New("store: this is the last admin who can log in")

// ErrOwnsRows is returned when a user who still owns documents, metadata or
// saved views would be removed. The error is an *OwnsRowsError with the counts.
var ErrOwnsRows = errors.New("store: the user still owns documents or metadata")

// OwnedRows counts the rows a user owns, per table. Deadlines belong to
// documents and are not counted on their own.
type OwnedRows struct {
	Documents, Tags, Correspondents, DocumentTypes, SavedViews int64
}

// Total is the number of owned rows.
func (o OwnedRows) Total() int64 {
	return o.Documents + o.Tags + o.Correspondents + o.DocumentTypes + o.SavedViews
}

// String lists the non-zero counts, like "3 documents, 1 tag".
func (o OwnedRows) String() string {
	var parts []string
	for _, c := range []struct {
		n             int64
		one, multiple string
	}{
		{o.Documents, "document", "documents"},
		{o.Tags, "tag", "tags"},
		{o.Correspondents, "correspondent", "correspondents"},
		{o.DocumentTypes, "document type", "document types"},
		{o.SavedViews, "saved view", "saved views"},
	} {
		switch {
		case c.n == 1:
			parts = append(parts, "1 "+c.one)
		case c.n > 1:
			parts = append(parts, fmt.Sprintf("%d %s", c.n, c.multiple))
		}
	}
	return strings.Join(parts, ", ")
}

// OwnsRowsError is returned by DeleteUser while the user owns rows.
// errors.Is(err, ErrOwnsRows) holds. Counts can be zero when a row was
// added concurrently and only the database refused the removal.
type OwnsRowsError struct {
	Counts OwnedRows
}

func (e *OwnsRowsError) Error() string {
	if e.Counts.Total() == 0 {
		return ErrOwnsRows.Error()
	}
	return "store: the user still owns " + e.Counts.String()
}

// Is makes errors.Is(err, ErrOwnsRows) true.
func (e *OwnsRowsError) Is(target error) bool { return target == ErrOwnsRows }

// User is an account that logs in and owns documents and metadata.
type User struct {
	ID                int64
	Name              string
	PasswordHash      string
	IsAdmin           bool
	LockedAt          *time.Time
	CreatedAt         time.Time
	PasswordChangedAt time.Time
	LastLoginAt       *time.Time
	// MustChangePassword is set for passwords generated by an admin.
	MustChangePassword bool
	// TwoFactorEnabled: the login needs a TOTP or recovery code.
	TwoFactorEnabled bool
	// TwoFactorVersion changes with every change of the 2FA state.
	TwoFactorVersion int64
}

func userFromDB(r db.User) *User {
	return &User{
		ID: r.ID, Name: r.Name, PasswordHash: r.PasswordHash, IsAdmin: r.IsAdmin,
		LockedAt: r.LockedAt, CreatedAt: r.CreatedAt, PasswordChangedAt: r.PasswordChangedAt,
		LastLoginAt: r.LastLoginAt, MustChangePassword: r.MustChangePassword,
		TwoFactorEnabled: r.TwoFactorEnabled, TwoFactorVersion: r.TwoFactorVersion,
	}
}

// CreateUser inserts a user. The name must already be normalized (see
// auth.NormalizeUserName); the database refuses other names. A taken name
// gives ErrNameTaken.
func (s *Store) CreateUser(ctx context.Context, name, passwordHash string, admin bool) (*User, error) {
	return s.createUser(ctx, name, passwordHash, admin, false)
}

// CreateUserWithGeneratedPassword is CreateUser for a password generated by
// an admin: the user must choose their own at the first login.
func (s *Store) CreateUserWithGeneratedPassword(ctx context.Context, name, passwordHash string, admin bool) (*User, error) {
	return s.createUser(ctx, name, passwordHash, admin, true)
}

func (s *Store) createUser(ctx context.Context, name, passwordHash string, admin, mustChange bool) (*User, error) {
	var u *User
	err := s.inTx(ctx, func(q *db.Queries) error {
		r, err := q.CreateUser(ctx, db.CreateUserParams{Name: name, PasswordHash: passwordHash, IsAdmin: admin, MustChangePassword: mustChange})
		if err != nil {
			return mapErr(err)
		}
		u = userFromDB(r)
		fillAuditTarget(ctx, TargetUser, u.ID)
		return nil
	})
	if err != nil {
		return nil, err
	}
	return u, nil
}

// GetUserByID looks up a user by ID.
func (s *Store) GetUserByID(ctx context.Context, id int64) (*User, error) {
	r, err := s.q.GetUserByID(ctx, id)
	if err != nil {
		return nil, mapErr(err)
	}
	return userFromDB(r), nil
}

// GetUserByName looks up a user by login name.
func (s *Store) GetUserByName(ctx context.Context, name string) (*User, error) {
	r, err := s.q.GetUserByName(ctx, name)
	if err != nil {
		return nil, mapErr(err)
	}
	return userFromDB(r), nil
}

// ListUsers returns all users ordered by name.
func (s *Store) ListUsers(ctx context.Context) ([]*User, error) {
	rows, err := s.q.ListUsers(ctx)
	if err != nil {
		return nil, err
	}
	out := make([]*User, 0, len(rows))
	for _, r := range rows {
		out = append(out, userFromDB(r))
	}
	return out, nil
}

// CountUsers returns the number of users.
func (s *Store) CountUsers(ctx context.Context) (int64, error) {
	return s.q.CountUsers(ctx)
}

// OwnedRowCounts returns the rows each user owns, by user ID.
func (s *Store) OwnedRowCounts(ctx context.Context) (map[int64]OwnedRows, error) {
	return ownedRowCounts(ctx, s.q)
}

func ownedRowCounts(ctx context.Context, q *db.Queries) (map[int64]OwnedRows, error) {
	rows, err := q.CountOwnedRows(ctx)
	if err != nil {
		return nil, err
	}
	out := make(map[int64]OwnedRows, len(rows))
	for _, r := range rows {
		out[r.ID] = OwnedRows{Documents: r.Documents, Tags: r.Tags, Correspondents: r.Correspondents, DocumentTypes: r.DocumentTypes, SavedViews: r.SavedViews}
	}
	return out, nil
}

// SetUserPassword stores a new password hash and ends all sessions of the
// user. With mustChange (a generated password) the user has to choose their
// own password at the next login.
func (s *Store) SetUserPassword(ctx context.Context, id int64, passwordHash string, mustChange bool) error {
	return s.ResetUserPassword(ctx, id, passwordHash, PasswordReset{MustChange: mustChange})
}

// PasswordReset says what else ResetUserPassword does.
type PasswordReset struct {
	// MustChange (a generated password): the user has to choose their own
	// password at the next login.
	MustChange bool
	// DropPasskeys removes the user's passkeys: after a compromise a new
	// password alone would not lock the attacker out. The pending audit
	// entry gets the number removed.
	DropPasskeys bool
	// RevokeAPIKeys revokes the user's API keys, for the same reason; the
	// pending audit entry gets the number revoked. By is the admin who
	// resets the password, recorded as the revoker (nil for the CLI), and
	// Now the time of the revocation (zero: time.Now).
	RevokeAPIKeys bool
	By            *int64
	Now           time.Time
}

// ResetUserPassword stores a new password hash, ends all sessions of the
// user and does what opts says.
func (s *Store) ResetUserPassword(ctx context.Context, id int64, passwordHash string, opts PasswordReset) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		if _, err := lockUserRow(ctx, q, id); err != nil {
			return err
		}
		if err := one(q.SetUserPassword(ctx, db.SetUserPasswordParams{ID: id, PasswordHash: passwordHash, MustChangePassword: opts.MustChange})); err != nil {
			return err
		}
		if opts.DropPasskeys {
			n, err := removePasskeys(ctx, q, id)
			if err != nil {
				return err
			}
			if e := auditFrom(ctx); e != nil {
				e.Detail("passkeysRemoved", n)
			}
		}
		if opts.RevokeAPIKeys {
			now := opts.Now
			if now.IsZero() {
				now = time.Now()
			}
			if _, err := revokeUserAPIKeys(ctx, q, id, opts.By, now); err != nil {
				return err
			}
		}
		return q.DeleteUserSessions(ctx, id)
	})
}

// ChangeOwnPassword stores the password a user chose themselves: it clears
// MustChangePassword and ends all their sessions except keepSession (the
// hash of the session that made the change).
func (s *Store) ChangeOwnPassword(ctx context.Context, id int64, passwordHash string, keepSession []byte) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		if err := one(q.SetUserPassword(ctx, db.SetUserPasswordParams{ID: id, PasswordHash: passwordHash})); err != nil {
			return err
		}
		return q.DeleteOtherSessions(ctx, db.DeleteOtherSessionsParams{UserID: id, ID: keepSession})
	})
}

// RehashUserPassword replaces the hash with a new hash of the same password,
// e.g. after the hash parameters changed. Sessions stay valid.
func (s *Store) RehashUserPassword(ctx context.Context, id int64, passwordHash string) error {
	return one(s.q.RehashUserPassword(ctx, db.RehashUserPasswordParams{ID: id, PasswordHash: passwordHash}))
}

// SetUserAdmin grants or revokes the admin role. Revoking it fails with
// ErrLastAdmin for the last unlocked admin.
func (s *Store) SetUserAdmin(ctx context.Context, id int64, admin bool) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		if !admin {
			if err := keepAnAdmin(ctx, q, id); err != nil {
				return err
			}
		}
		return one(q.SetUserAdmin(ctx, db.SetUserAdminParams{ID: id, IsAdmin: admin}))
	})
}

// SetUserLocked locks or unlocks a user. Locking ends all sessions of the
// user and fails with ErrLastAdmin for the last unlocked admin.
func (s *Store) SetUserLocked(ctx context.Context, id int64, locked bool) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		if locked {
			if err := keepAnAdmin(ctx, q, id); err != nil {
				return err
			}
		}
		if err := one(q.SetUserLocked(ctx, db.SetUserLockedParams{ID: id, Locked: locked})); err != nil {
			return err
		}
		if locked {
			return q.DeleteUserSessions(ctx, id)
		}
		return nil
	})
}

// DeleteUser deletes a user and their sessions. It fails with ErrLastAdmin
// for the last unlocked admin and with an *OwnsRowsError while the user
// owns documents or metadata.
func (s *Store) DeleteUser(ctx context.Context, id int64) error {
	err := s.inTx(ctx, func(q *db.Queries) error {
		if err := keepAnAdmin(ctx, q, id); err != nil {
			return err
		}
		if _, err := q.LockUser(ctx, id); err != nil {
			return mapErr(err)
		}
		counts, err := ownedRowCounts(ctx, q)
		if err != nil {
			return err
		}
		if c := counts[id]; c.Total() > 0 {
			return &OwnsRowsError{Counts: c}
		}
		// The sessions, passkeys and API keys go with the user (ON DELETE
		// CASCADE).
		if e := auditFrom(ctx); e != nil {
			n, err := q.CountActiveAPIKeys(ctx, db.CountActiveAPIKeysParams{UserID: id, Now: time.Now()})
			if err != nil {
				return err
			}
			e.Detail("apiKeysRemoved", n)
		}
		return one(q.DeleteUser(ctx, id))
	})
	if isRestrictViolation(err) && !errors.Is(err, ErrAuditUnavailable) {
		// A row added concurrently, or an owned table the counts do not
		// know yet: the foreign key refused the removal.
		return s.ownsRowsError(ctx, id)
	}
	return err
}

// ownsRowsError builds the error for a removal the database refused,
// with the counts as they are now.
func (s *Store) ownsRowsError(ctx context.Context, id int64) error {
	counts, err := s.OwnedRowCounts(ctx)
	if err != nil {
		return &OwnsRowsError{}
	}
	return &OwnsRowsError{Counts: counts[id]}
}

// isRestrictViolation reports whether err is a refused delete of a
// referenced row. PostgreSQL 18 reports ON DELETE RESTRICT as
// restrict_violation (23001), older versions as foreign_key_violation
// (23503).
func isRestrictViolation(err error) bool {
	var pgErr *pgconn.PgError
	return errors.As(err, &pgErr) && (pgErr.Code == "23001" || pgErr.Code == "23503")
}

// keepAnAdmin fails if user id is the only unlocked admin. The admin rows
// stay locked until the transaction ends.
func keepAnAdmin(ctx context.Context, q *db.Queries, id int64) error {
	admins, err := q.LockActiveAdmins(ctx)
	if err != nil {
		return err
	}
	if len(admins) == 1 && admins[0] == id {
		return ErrLastAdmin
	}
	return nil
}

// Session is a valid login session with its user.
type Session struct {
	UserID             int64
	UserName           string
	IsAdmin            bool
	MustChangePassword bool
	TwoFactorEnabled   bool
	LastSeenAt         time.Time
}

// StartSession stores a new session after a password login and records the
// login time. now is the server clock.
func (s *Store) StartSession(ctx context.Context, idHash []byte, userID int64, now, expiresAt time.Time, userAgent string) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		if err := q.CreateSession(ctx, db.CreateSessionParams{ID: idHash, UserID: userID, Now: now, ExpiresAt: expiresAt, UserAgent: userAgent}); err != nil {
			return err
		}
		return q.RecordLogin(ctx, db.RecordLoginParams{ID: userID, At: now})
	})
}

// CreateSession stores a session under the hash of its token, without
// recording a login (tests and later login methods).
func (s *Store) CreateSession(ctx context.Context, idHash []byte, userID int64, now, expiresAt time.Time, userAgent string) error {
	return s.q.CreateSession(ctx, db.CreateSessionParams{ID: idHash, UserID: userID, Now: now, ExpiresAt: expiresAt, UserAgent: userAgent})
}

// GetSession returns a session that has not expired at now, was used after
// idleCutoff and belongs to an unlocked user; otherwise ErrNotFound.
func (s *Store) GetSession(ctx context.Context, idHash []byte, now, idleCutoff time.Time) (*Session, error) {
	r, err := s.q.GetSession(ctx, db.GetSessionParams{ID: idHash, Now: now, IdleCutoff: idleCutoff})
	if err != nil {
		return nil, mapErr(err)
	}
	return &Session{UserID: r.UserID, UserName: r.Name, IsAdmin: r.IsAdmin, MustChangePassword: r.MustChangePassword, TwoFactorEnabled: r.TwoFactorEnabled, LastSeenAt: r.LastSeenAt}, nil
}

// TouchSession records that a session was used at now.
func (s *Store) TouchSession(ctx context.Context, idHash []byte, now time.Time) error {
	return s.q.TouchSession(ctx, db.TouchSessionParams{ID: idHash, Now: now})
}

// EndSession ends a session at logout, together with the audit entry of
// ctx.
func (s *Store) EndSession(ctx context.Context, idHash []byte) error {
	return s.inTx(ctx, func(q *db.Queries) error {
		return q.DeleteSession(ctx, idHash)
	})
}

// DeleteSession ends a session.
func (s *Store) DeleteSession(ctx context.Context, idHash []byte) error {
	return s.q.DeleteSession(ctx, idHash)
}

// DeleteExpiredSessions removes sessions expired at now or unused since
// idleCutoff and returns how many were removed.
func (s *Store) DeleteExpiredSessions(ctx context.Context, now, idleCutoff time.Time) (int64, error) {
	return s.q.DeleteExpiredSessions(ctx, db.DeleteExpiredSessionsParams{Now: now, IdleCutoff: idleCutoff})
}

// one turns the row count of an update or delete into ErrNotFound when no
// row was affected.
func one(n int64, err error) error {
	if err != nil {
		return err
	}
	if n == 0 {
		return ErrNotFound
	}
	return nil
}
