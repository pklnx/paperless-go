func main() {
	dbURL := flag.String("db", os.Getenv(config.EnvDatabaseURL), "PostgreSQL URL of a user with CREATEDB")
	listen := flag.String("listen", "127.0.0.1:18280", "address of the web UI")
	flag.Parse()
	log := slog.New(slog.NewTextHandler(os.Stderr, &slog.HandlerOptions{Level: slog.LevelWarn}))
	if err := run(*dbURL, *listen, log); err != nil {
		fmt.Fprintln(os.Stderr, "demo:", err)
		os.Exit(1)
	}
}

func run(dbURL, listen string, log *slog.Logger) error {
	if dbURL == "" {
		return errors.New("set -db or " + config.EnvDatabaseURL)
	}
	// Passkeys need a host name: the demo is meant for localhost.
	_, port, err := net.SplitHostPort(listen)
	if err != nil {
		return err
	}
	publicURL := "http://localhost:" + port

	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()

	demoURL, dropDB, err := createDatabase(ctx, dbURL, log)
	if err != nil {
		return err
	}
	defer dropDB()
	dataDir, err := os.MkdirTemp("", "paperless-go-demo-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(dataDir) }()

	st, err := store.Open(ctx, demoURL, blobstore.OpenFiles(dataDir))
	if err != nil {
		return err
	}
	defer st.Close()
	if _, err := st.Migrate(ctx); err != nil {
		return err
	}
	inst, err := st.Installation(ctx)
	if err != nil {
		return err
	}
	// As migrate does: the sweep's walk accepts the fresh data directory.
	if _, err := sweep.BindFresh(dataDir, inst.ID); err != nil {
		return err
	}
	blobs, err := blobstore.New(dataDir)
	if err != nil {
		return err
	}
	key := make([]byte, crypto.KeySize)
	if _, err := rand.Read(key); err != nil {
		return err
	}
	sealer, err := crypto.NewSealer(key)
	if err != nil {
		return err
	}

	ids, err := addUsers(ctx, st, sealer, key)
	if err != nil {
		return err
	}
	if err := seed(ctx, st, blobs, ids); err != nil {
		return err
	}

	wd, err := process.OpenWorkDir(dataDir, log)
	if err != nil {
		return err
	}
	defer func() { _ = wd.Close() }()
	tools := fakeTools{}
	if err := process.CheckLanguages(ctx, tools, wd.Path(), process.DefaultLanguages); err != nil {
		return err
	}
	worker := &process.Worker{
		Store: st, Blobs: blobs, WorkDir: wd,
		Pipeline: &process.Pipeline{Runner: tools, Languages: process.DefaultLanguages, Jobs: 1},
		// Without a timeout every attempt would end at once.
		Log: log, Workers: 1, Timeout: config.DefaultOCRTimeout,
	}
	// The seed is processed before the server listens, so the first page
	// shows finished documents.
	if err := processSeed(ctx, worker); err != nil {
		return err
	}

	runCtx, cancel := context.WithCancel(ctx)
	defer cancel()
	var background sync.WaitGroup
	defer background.Wait()
	background.Go(func() { worker.Run(runCtx) })
	wake, wakeSweeper := sweep.Wake()
	sweeper := &sweep.Sweeper{Store: st, Blobs: blobs, Log: log, Now: st.Now, Retention: st.TrashRetention}
	ticker := time.NewTicker(sweep.DefaultInterval)
	defer ticker.Stop()
	background.Go(func() { sweeper.Run(runCtx, ticker.C, wake) })

	srv := web.New(st, log, web.Options{
		Sealer: sealer, SecretKey: key, PublicURL: publicURL, Blobs: blobs, SweepWake: wakeSweeper,
	})
	// The address is printed only once it can be bound: web.Server binds
	// it itself (ListenAndServe), so the demo checks it first. Taken in
	// the moment between, ListenAndServe fails and the demo exits 1.
	ln, err := net.Listen("tcp", listen)
	if err != nil {
		cancel()
		return err
	}
	if err := ln.Close(); err != nil {
		cancel()
		return err
	}
	// The password and the TOTP secret are not printed: they are public,
	// but a password does not go into output (CodeQL). They are in the
	// users above and in web/e2e/demo.ts.
	fmt.Printf("demo UI on %s, log in as %q: password and TOTP secret in tools/demo/main.go (Ctrl-C to stop and delete the demo data)\n",
		publicURL, demoAdmin.name)
	err = srv.ListenAndServe(runCtx, listen)
	cancel()
	if err != nil && !errors.Is(err, http.ErrServerClosed) {
		return err
	}
	return nil
}

// addUsers creates the demo users and returns their IDs by name.
func addUsers(ctx context.Context, st *store.Store, sealer *crypto.Sealer, key []byte) (map[string]int64, error) {
	hasher := auth.NewHasher(auth.DefaultParams)
	ids := make(map[string]int64, len(users))
	for _, u := range users {
		hash, err := hasher.Hash(ctx, u.password)
		if err != nil {
			return nil, err
		}
		create := st.CreateUser
		if u.mustChange {
			create = st.CreateUserWithGeneratedPassword
		}
		row, err := create(ctx, u.name, hash, u.admin)
		if err != nil {
			return nil, fmt.Errorf("user %s: %w", u.name, err)
		}
		ids[u.name] = row.ID
		if u.totp != "" {
			at := time.Now().Add(u.totpAt)
			code, err := auth.GenerateTOTP(u.totp, at)
			if err != nil {
				return nil, err
			}
			if err := st.BeginTwoFactorSetup(ctx, row.ID, u.totp, sealer); err != nil {
				return nil, err
			}
			if err := st.ConfirmTwoFactorSetup(ctx, row.ID, code, at, sealer, nil, key); err != nil {
				return nil, fmt.Errorf("2FA of %s: %w", u.name, err)
			}
		}
		if u.locked {
			if err := st.SetUserLocked(ctx, row.ID, true); err != nil {
				return nil, err
			}
		}
	}
	return ids, nil
}

// processSeed processes the queued documents one after another until none
// is due, as `process --until-empty` does. Every seed document must be
// done: the tests rely on their text.
func processSeed(ctx context.Context, w *process.Worker) error {
	for {
		outcome, err := w.RunOnce(ctx)
		if err != nil {
			return err
		}
		switch outcome {
		case process.NoJob:
			return nil
		case process.Done:
		default:
			return fmt.Errorf("a seed document was not processed (outcome %d)", outcome)
		}
	}
}

// createDatabase creates a uniquely named database on the server of base
// and returns its URL and a function that drops it. The drop opens a
// connection of its own: one held for the whole run could have been
// closed by the server meanwhile. A failed drop is logged.
func createDatabase(ctx context.Context, base string, log *slog.Logger) (string, func(), error) {
	// The URL first: nothing is created when it cannot be read.
	u, err := url.Parse(base)
	if err != nil {
		return "", nil, fmt.Errorf("read -db: %w", err)
	}
	suffix := make([]byte, 4)
	if _, err := rand.Read(suffix); err != nil {
		return "", nil, err
	}
	name := "paperless_demo_" + hex.EncodeToString(suffix)
	ident := pgx.Identifier{name}.Sanitize()
	admin, err := pgx.Connect(ctx, base)
	if err != nil {
		return "", nil, err
	}
	_, err = admin.Exec(ctx, "CREATE DATABASE "+ident)
	_ = admin.Close(ctx)
	if err != nil {
		return "", nil, fmt.Errorf("create demo database (the user needs CREATEDB): %w", err)
	}
	u.Path = "/" + name
	drop := func() {
		// Not the run's context: it has ended when the demo stops.
		bg, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		conn, err := pgx.Connect(bg, base)
		if err == nil {
			_, err = conn.Exec(bg, "DROP DATABASE "+ident+" WITH (FORCE)")
			_ = conn.Close(bg)
		}
		if err != nil {
			log.Error("drop the demo database; drop it by hand", "database", name, "err", err)
		}
	}
	return u.String(), drop, nil
}
