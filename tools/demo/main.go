// Command demo runs the web UI with made-up documents, for the end-to-end
// tests in web/e2e, for screenshots and for trying the UI. It is never
// built into the image or a release.
//
// It creates a temporary database next to the one in -db (the user needs
// CREATEDB) and a temporary data directory, adds users, tags,
// correspondents, document types and generated documents, processes them
// with stand-in tools (tools.go: no OCR tools, no network), and serves the
// UI with a processing worker and the trash's sweeper. On exit (Ctrl-C or
// SIGTERM) the database and the data directory are deleted. Nothing
// touches the database named in -db itself.
//
// The wiring repeats serve's (newServeCmd in cmd/paperless-go/commands.go);
// compare with it when serve gains a component.
