// demoUser is a login of the demo. web/e2e/demo.ts has the same values.
// These are public demo logins; the TOTP secrets are example strings.
type demoUser struct {
	name, password string
	admin          bool
	// totp is the 2FA secret; empty means no 2FA.
	totp string
	// totpAt is when the 2FA setup was confirmed: its time step is used.
	totpAt time.Duration
	// mustChange: the password was generated by an admin.
	mustChange bool
	locked     bool
}

